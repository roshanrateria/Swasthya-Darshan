// Fill in missing translations with English
Object.keys(TRANSLATIONS).forEach(lang => {
    if (lang !== 'en') {
        Object.keys(TRANSLATIONS.en).forEach(key => {
            if (!TRANSLATIONS[lang][key]) {
                TRANSLATIONS[lang][key] = TRANSLATIONS.en[key];
            }
        });
    }
});

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
    const [language, setLanguage] = useState(() => {
        const saved = localStorage.getItem('swasthya_language');
        return saved || 'hi';
    });

    useEffect(() => {
        localStorage.setItem('swasthya_language', language);
    }, [language]);

    const t = (key) => {
        return TRANSLATIONS[language]?.[key] || TRANSLATIONS.en[key] || key;
    };

    const value = {
        language,
        setLanguage,
        t,
        languages: LANGUAGES,
        currentLanguage: LANGUAGES.find(l => l.code === language) || LANGUAGES[0],
    };

    return (
        <LanguageContext.Provider value={value}>
            {children}
        </LanguageContext.Provider>
    );
}

export function useLanguage() {
    const context = useContext(LanguageContext);
    if (!context) {
        return { 
            t: (key) => key, 
            language: 'en', 
            setLanguage: () => {}, 
            languages: [], 
            currentLanguage: { code: 'en', name: 'English' }
        };
    }
    return context;
}
